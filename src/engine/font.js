function compile(src, capH) {
  const out = {};
  for (const [k, v] of Object.entries(src)) {
    const g = Array.isArray(v) ? { dy: 0, rows: v } : v;
    const w = g.rows.reduce((m, r) => Math.max(m, r.length), 0);
    out[k] = { w, dy: g.dy || 0, rows: g.rows };
  }
  return { glyphs: out, capH, space: 1 };
}

