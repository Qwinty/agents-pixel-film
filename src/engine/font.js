export function textWidth(font, str, spacing = 1) {
  let w = 0, n = 0;
  for (const ch of str) {
    const g = font.glyphs[ch] || font.glyphs[ch.toLowerCase()] || font.glyphs['?'] || font.glyphs[' '];
    w += g.w; n++;
  }
  return w + Math.max(0, n - 1) * spacing;
}

/** Draw text with top-left at (x,y) = cap top. Returns advance width. opts: spacing, emit */
export function drawText(art, font, str, x, y, color, opts = {}) {
  const spacing = opts.spacing ?? 1;
  let cx = Math.round(x);
  y = Math.round(y);
  let idx = 0;
  for (const ch of str) {
    const g = font.glyphs[ch] || font.glyphs[ch.toLowerCase()] || font.glyphs['?'] || font.glyphs[' '];
    const c = typeof color === 'function' ? color(idx, ch) : color;
    if (c >= 0) {
      for (let j = 0; j < g.rows.length; j++) {
        const row = g.rows[j];
        for (let i = 0; i < row.length; i++) if (row[i] === '#') art.put(cx + i, y + j + g.dy, c);
      }
    }
    cx += g.w + spacing;
    idx++;
  }
  return cx - Math.round(x) - spacing;
}
